-- Stores one FSRS learning state per user and flashcard
CREATE TABLE flashcard_review_states
(
    review_state_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    flashcard_id BIGINT NOT NULL,
    state VARCHAR(20) NOT NULL DEFAULT 'NEW',
    due_at TIMESTAMPTZ,
    last_reviewed_at TIMESTAMPTZ,
    stability DOUBLE PRECISION,
    difficulty DOUBLE PRECISION,
    scheduled_days DOUBLE PRECISION,
    learning_step INTEGER,
    review_count INTEGER NOT NULL DEFAULT 0,
    lapses INTEGER NOT NULL DEFAULT 0,
    fsrs_card_data TEXT,
    algorithm_version VARCHAR(20) NOT NULL DEFAULT 'FSRS-6',
    version BIGINT NOT NULL DEFAULT 0,

    CONSTRAINT fk_flashcard_review_states_user
        FOREIGN KEY (user_id) REFERENCES "user" (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_flashcard_review_states_flashcard
        FOREIGN KEY (flashcard_id) REFERENCES flashcard (flashcard_id) ON DELETE CASCADE,
    CONSTRAINT uk_flashcard_review_states_user_flashcard
        UNIQUE (user_id, flashcard_id),
    CONSTRAINT chk_flashcard_review_states_state
        CHECK (state IN ('NEW', 'LEARNING', 'REVIEW', 'RELEARNING')),
    CONSTRAINT chk_flashcard_review_states_stability
        CHECK (stability IS NULL OR stability >= 0),
    CONSTRAINT chk_flashcard_review_states_difficulty
        CHECK (difficulty IS NULL OR difficulty BETWEEN 1 AND 10),
    CONSTRAINT chk_flashcard_review_states_scheduled_days
        CHECK (scheduled_days IS NULL OR scheduled_days >= 0),
    CONSTRAINT chk_flashcard_review_states_learning_step
        CHECK (learning_step IS NULL OR learning_step >= 0),
    CONSTRAINT chk_flashcard_review_states_review_count
        CHECK (review_count >= 0),
    CONSTRAINT chk_flashcard_review_states_lapses
        CHECK (lapses >= 0 AND lapses <= review_count)
);

CREATE INDEX idx_flashcard_review_states_user_due
    ON flashcard_review_states (user_id, due_at)
    WHERE due_at IS NOT NULL;

-- Stores immutable review events. Deleting a review state deletes its history
CREATE TABLE flashcard_review_logs
(
    review_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_state_id BIGINT NOT NULL,
    rating VARCHAR(10) NOT NULL,
    reviewed_at TIMESTAMPTZ NOT NULL,
    previous_due_at TIMESTAMPTZ,
    next_due_at TIMESTAMPTZ NOT NULL,
    stage_before VARCHAR(20) NOT NULL,
    stage_after VARCHAR(20) NOT NULL,
    card_data_before TEXT,
    card_data_after TEXT NOT NULL,
    algorithm_version VARCHAR(20) NOT NULL,
    request_id UUID NOT NULL,

    CONSTRAINT fk_flashcard_review_logs_state
        FOREIGN KEY (review_state_id)
            REFERENCES flashcard_review_states (review_state_id)
            ON DELETE CASCADE,
    CONSTRAINT uk_flashcard_review_logs_request_id UNIQUE (request_id),
    CONSTRAINT chk_flashcard_review_logs_rating
        CHECK (rating IN ('AGAIN', 'HARD', 'GOOD', 'EASY')),
    CONSTRAINT chk_flashcard_review_logs_stage_before
        CHECK (stage_before IN ('NEW', 'LEARNING', 'REVIEW', 'RELEARNING')),
    CONSTRAINT chk_flashcard_review_logs_stage_after
        CHECK (stage_after IN ('NEW', 'LEARNING', 'REVIEW', 'RELEARNING')));

CREATE INDEX idx_flashcard_review_logs_state_reviewed
    ON flashcard_review_logs (review_state_id, reviewed_at DESC);

-- Stores per-user study preferences; defaults are applied when a row is created
CREATE TABLE user_review_settings
(
    user_id BIGINT PRIMARY KEY,
    desired_retention DOUBLE PRECISION NOT NULL DEFAULT 0.90,
    new_cards_per_day INTEGER NOT NULL DEFAULT 20,
    review_limit_per_day INTEGER NOT NULL DEFAULT 200,
    timezone VARCHAR(64) NOT NULL DEFAULT 'UTC',
    fsrs_parameters TEXT,
    algorithm_version VARCHAR(20) NOT NULL DEFAULT 'FSRS-6',

    CONSTRAINT fk_user_review_settings_user
        FOREIGN KEY (user_id) REFERENCES "user" (user_id) ON DELETE CASCADE,
    CONSTRAINT chk_user_review_settings_retention
        CHECK (desired_retention > 0 AND desired_retention < 1),
    CONSTRAINT chk_user_review_settings_daily_limits
        CHECK (new_cards_per_day >= 0 AND review_limit_per_day >= 0),
    CONSTRAINT chk_user_review_settings_timezone
        CHECK (length(trim(timezone)) > 0)
);